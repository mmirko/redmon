package redmon

import (
	"encoding/json"
	"fmt"
	"os"

	"github.com/mmirko/redmon/pkg/embredmon"
)

type RedmonConfig struct {
	EmitDebug bool `json:"debug"`
	Verbose   bool `json:"verbose"`
	Sources   []struct {
		Name     string `json:"name"`
		Stype    string `json:"type"`
		Endpoint string `json:"endpoint"`
		Key      string `json:"key"`
		Db       string `json:"db"`
	} `json:"sources"`
	Sensors        []SensorConfig        `json:"sensors"`
	VirtualSensors []VirtualSensorConfig `json:"virtual_sensors"`
}

func (c *RedmonConfig) String() string {
	return fmt.Sprint(*c)
}

func LoadConfig(configFile string, configEmbedded embredmon.AutoGenerated) (*RedmonConfig, error) {
	c := new(RedmonConfig)

	if configFile != "" {
		c.Debug("Loading configuration from the file \"" + configFile + "\"")
		content, err := os.ReadFile(configFile)
		if err != nil {
			c.Alert(err)
			return nil, err
		}

		if json.Unmarshal(content, c) != nil {
			c.Alert("Failed to parse configuration")
			return nil, fmt.Errorf("failed to parse configuration")
		}

		c.Debug("Configuration loaded: " + c.String())
	} else {
		c.Debug("Loading configuration from the embedded configuration")

		c.Sources = make([]struct {
			Name     string `json:"name"`
			Stype    string `json:"type"`
			Endpoint string `json:"endpoint"`
			Key      string `json:"key"`
			Db       string `json:"db"`
		}, len(configEmbedded.Sources))

		for i, source := range configEmbedded.Sources {
			c.Sources[i].Name = source.Name
			c.Sources[i].Stype = source.Type
			c.Sources[i].Endpoint = source.Endpoint
			c.Sources[i].Key = source.Key
			c.Sources[i].Db = source.Db
		}

		c.Debug("Configuration loaded: " + c.String())
	}
	return c, nil
}
